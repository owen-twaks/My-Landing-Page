import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

function dimensions(buf) {
  if (buf.readUInt32BE(0) === 0x89504e47) {
    return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
  }
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i < buf.length) {
      if (buf[i] !== 0xff) { i++; continue; }
      const marker = buf[i + 1];
      if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) { i += 2; continue; }
      const len = buf.readUInt16BE(i + 2);
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
        return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
      }
      i += 2 + len;
    }
  }
  return null;
}

const baseDir = path.join(process.cwd(), 'public');
const subdirs = ['images', 'image2'];
const files = [];
for (const sub of subdirs) {
  const dir = path.join(baseDir, sub);
  const entries = await readdir(dir);
  for (const f of entries) {
    if (/\.(jpe?g|png)$/i.test(f)) files.push(`${sub}/${f}`);
  }
}
files.sort();

const rows = [];
const skipped = [];
for (const rel of files) {
  const buf = await readFile(path.join(baseDir, rel));
  const dims = dimensions(buf);
  if (!dims) { skipped.push(rel); continue; }
  const prefix = rel.startsWith('image2/') ? '/image2/' : '/images/';
  const name = rel.split('/').pop();
  rows.push(`  '${prefix}${name}': { width: ${dims.width}, height: ${dims.height} },`);
}

const out = `/**\n * Intrinsic dimensions of every image in public/images and public/image2, so <Img> can set\n * width/height attributes and reserve space before the file loads (avoids CLS).\n * Generated by scripts/image-dims.mjs — do not edit by hand.\n */\nexport const imageSizes = {\n${rows.join('\n')}\n};\n`;

await writeFile(path.join('src', 'data', 'images.ts'), out, 'utf8');
console.log(`✓ src/data/images.ts updated — ${rows.length} images${skipped.length ? ` (skipped: ${skipped.join(', ')})` : ''}`);
